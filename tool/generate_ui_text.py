#!/usr/bin/env python3
"""Generate the bounded lookup for app-owned labels and legacy status strings.

The controller stays independent of Flutter. Do not apply this lookup to peer
names, message bodies, addresses, keys or other opaque user/network content.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
catalog = json.loads((ROOT / "lib/l10n/app_en.arb").read_text())
quote = lambda value: json.dumps(value, ensure_ascii=False).replace("$", r"\$")
static = {}
dynamic = []
for key, value in catalog.items():
    if key.startswith("@") or not isinstance(value, str):
        continue
    meta = catalog.get("@" + key, {})
    if meta.get("x-ui-text-lookup") is False:
        continue
    pattern = meta.get("x-ui-template", value)
    if re.search(r"\{\w+\s*,", pattern):
        continue
    names = re.findall(r"\{(\w+)\}", pattern)
    if not names:
        static.setdefault(pattern, key)
    elif len(names) <= 8 and len(set(names)) == len(names):
        parts = re.split(r"\{\w+\}", pattern)
        if any(not part for part in parts[1:-1]):
            continue
        dynamic.append((pattern, key, names, parts, meta))
lines = ["// Generated by tool/generate_ui_text.py. Do not edit by hand.",
         "import 'package:flutter/widgets.dart';", "import '../../l10n/app_localizations.dart';",
         "import '../app_locales.dart';", "", "/// Localize only app-owned labels/statuses; keep unknown diagnostics intact.",
         "String localizedUiText(BuildContext? context, String text) {",
         "  if (text.length > 16384) return text;", "  final strings = l10nOf(context);",
         "  final direct = _lookup(strings, text);", "  if (direct != null) return direct;",
         "  for (final prefix in const ['Bad state: ', 'Exception: ', 'FormatException: ']) {",
         "    if (text.startsWith(prefix)) {",
         "      return _lookup(strings, text.substring(prefix.length)) ?? text;", "    }", "  }",
         "  return text;", "}", "", "String? _lookup(AppLocalizations s, String text) {", "  switch (text) {"]
for value, key in sorted(static.items()):
    lines.append(f"    case {quote(value)}: return s.{key};")
lines.extend(["  }"])
for pattern, key, names, parts, meta in sorted(dynamic, key=lambda row: -sum(map(len, row[3]))):
    lines.extend(["  {", "    final values = _match(text, [" + ", ".join(map(quote, parts)) + "]);"])
    lines.append("    if (values != null) {")
    lines.append("      if (values.isEmpty) return null;")
    params = []
    guards = []
    for index, name in enumerate(names):
        kind = meta.get("placeholders", {}).get(name, {}).get("type", "String")
        expr = f"values[{index}]"
        if kind in ("int", "double", "num"):
            lines.append(f"      final p{index} = {kind}.tryParse({expr});")
            guards.append(f"p{index} != null" + (f" && p{index}.isFinite" if kind != "int" else ""))
            expr = f"p{index}"
        params.append(expr)
    call = f"s.{key}({', '.join(params)})"
    if guards:
        lines.append("      if (" + " && ".join(guards) + f") return {call};")
    else:
        lines.append(f"      return {call};")
    lines.extend(["    }", "  }"])
lines.extend(["  return null;", "}", "", "// null: not this template; empty: ambiguous, preserve the entire original.",
"List<String>? _match(String text, List<String> parts) {",
"  if (!text.startsWith(parts.first) || !text.endsWith(parts.last)) return null;",
"  var offset = parts.first.length;",
"  final end = text.length - parts.last.length;",
"  if (end < offset) return null;",
"  final values = <String>[];",
"  for (var index = 1; index < parts.length - 1; index++) {",
"    final delimiter = parts[index];",
"    final next = text.indexOf(delimiter, offset);",
"    if (next < offset || next > end) return null;",
"    final again = text.indexOf(delimiter, next + 1);",
"    if (again >= 0 && again <= end) return const [];",
"    values.add(text.substring(offset, next));",
"    offset = next + delimiter.length;",
"  }",
"  if (offset > end) return null;",
"  values.add(text.substring(offset, end));",
"  return values;", "}", ""])
(ROOT / "lib/src/ui/localized_ui_text.dart").write_text("\n".join(lines))
print(f"Generated {len(static)} labels and {len(dynamic)} status templates")
